"""Generate design/palette.css (tokens for the slides) and design/palette.html (swatch sheet)
from design/palette.json, so the palette has one source of truth.

Run:  python tools/build_palette.py
"""
import json, os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
pal = json.load(open(os.path.join(ROOT, "design", "palette.json")))

css = ["/* Generated by tools/build_palette.py from design/palette.json. Edit the JSON, not this file. */", ":root {"]
for k, v in pal["program"].items():
    slug = k.replace("_", "-")
    css.append(f"  --{slug}: {v['base']};      /* {v['label']} */")
    css.append(f"  --{slug}-tint: {v['tint']};")
for k, v in pal["neutral"].items():
    css.append(f"  --{k}: {v};")
css.append("}")
open(os.path.join(ROOT, "design", "palette.css"), "w").write("\n".join(css) + "\n")

cards = "".join(
    f'<div class="card"><div class="sw" style="background:{v["base"]}"></div>'
    f'<div class="sw t" style="background:{v["tint"]}"></div>'
    f'<b>{v["label"]}</b><code>--{k.replace("_", "-")}  {v["base"]} / {v["tint"]}</code></div>'
    for k, v in pal["program"].items())
html = f"""<!doctype html><meta charset="utf-8"><title>Program Palette</title>
<link rel="stylesheet" href="palette.css">
<style>
body{{font:15px/1.4 'Helvetica Neue',Arial,sans-serif;background:var(--paper);color:var(--ink);margin:32px}}
h1{{font-size:24px;margin:0 0 4px}} p{{color:var(--muted);margin:0 0 20px;max-width:60ch}}
.grid{{display:grid;grid-template-columns:repeat(auto-fill,minmax(220px,1fr));gap:14px}}
.card{{background:#fff;border:1px solid var(--line);border-radius:8px;padding:12px}}
.sw{{height:56px;border-radius:6px}} .sw.t{{height:22px;margin:4px 0 8px}}
code{{display:block;font-size:12px;color:var(--muted);margin-top:4px}}
</style>
<h1>Program Palette</h1>
<p>One hue per program element, used for nothing else, on every slide and drawing. Level 1 / minimum
investment uses the solid base color; Ultimate / future phases use the tint with a hatch.</p>
<div class="grid">{cards}</div>
"""
open(os.path.join(ROOT, "design", "palette.html"), "w").write(html)
print("wrote design/palette.css and design/palette.html")
