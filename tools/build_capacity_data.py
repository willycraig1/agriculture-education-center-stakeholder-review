"""Write slides/data/pasture-capacity.js from source/Clark_Farm_Pasture_Calculations.xlsx.

The worksheet holds paddock acreages and canopy splits. Stocking rates are UF/IFAS AN155 planning
values: conservative 4 ac/CE open and 25 ac/CE wooded; improved/rotational 2 and 10. The three Levels:
  Level 1  site pasture,          conservative management  (minimum to operate)
  Level 2  site pasture,          improved rotational management
  Level 3  site + bonus pasture,  improved rotational management (best case)
Output is a plain JS file (window.PASTURE_CAPACITY = {...}) so the slide also works from file://.

Run:  python tools/build_capacity_data.py   (needs openpyxl)
"""
import json, os, re
import openpyxl

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
XLSX = os.path.join(ROOT, "source", "Clark_Farm_Pasture_Calculations.xlsx")
OUT = os.path.join(ROOT, "slides", "data", "pasture-capacity.js")

# the switch lives in tools/siteframe.py; read it without importing that module (it parses the CAD sheets)
MAIN_PARCEL_ONLY = re.search(r"^MAIN_PARCEL_ONLY = (True|False)", open(os.path.join(ROOT, "tools", "siteframe.py")).read(), re.M).group(1) == "True"
RATES = {"conservative": {"open": 4, "wooded": 25}, "improved": {"open": 2, "wooded": 10}}

# Paddock acres: drawings/data/paddocks.json when it exists (tools/build_site_map.py: the fencing plan's figure for
# each paddock, adjusted where a fence has since been redrawn), with the worksheet's dense-woods share for each.
# Otherwise the worksheet's own acres.
PADS = os.path.join(ROOT, "drawings", "data", "paddocks.json")
paddocks = []
if os.path.exists(PADS):
    for q in json.load(open(PADS))["paddocks"]:
        paddocks.append({"group": q["group"], "acres": q["acres"], "wooded": q["acres"] * q["dense"], "open": q["acres"] * (1 - q["dense"])})
else:
    for row in openpyxl.load_workbook(XLSX)["Paddock Detail"].iter_rows(min_row=5, max_row=20, values_only=True):
        area, ac, dense = row[0], row[1], row[2] or 0
        if area and ac:
            paddocks.append({"group": "site" if area == "Site Pasture" else "bonus", "acres": float(ac),
                             "wooded": float(ac) * dense, "open": float(ac) * (1 - dense)})


def sums(groups):
    p = [x for x in paddocks if x["group"] in groups]
    return {g: {"open": sum(x["open"] for x in p if x["group"] == g),
                "wooded": sum(x["wooded"] for x in p if x["group"] == g)} for g in groups}


def level(n, name, sub, groups, mgmt):
    s = sums(groups)
    open_ac = sum(v["open"] for v in s.values())
    wooded_ac = sum(v["wooded"] for v in s.values())
    r = RATES[mgmt]
    ce_open, ce_wooded = open_ac / r["open"], wooded_ac / r["wooded"]
    return {"level": n, "name": name, "subtitle": sub, "management": mgmt, "groups": groups,
            "split": {g: {k: round(v, 2) for k, v in d.items()} for g, d in s.items()},
            "acres": round(open_ac + wooded_ac, 1), "open": round(open_ac, 1), "wooded": round(wooded_ac, 1),
            "rate_open": r["open"], "rate_wooded": r["wooded"],
            "ce_open": round(ce_open, 1), "ce_wooded": round(ce_wooded, 1),
            "ce": round(ce_open + ce_wooded, 1), "ce_planning": round(ce_open + ce_wooded)}


data = {
    "source": "source/Clark_Farm_Pasture_Calculations.xlsx · UF/IFAS AN155 Stocking Rate Decisions" + (" · paddock acres as fenced (drawings/data/paddocks.json)" if os.path.exists(PADS) else ""),
    "levels": [
        level(1, "Level 1", "Minimum to operate", ["site"], "conservative"),
        level(2, "Level 2", "Better management", ["site"], "improved"),
        # main parcel only (siteframe.MAIN_PARCEL_ONLY, owner 2026-10-19): no bonus pasture, so Level 3 grazes the site
        # pasture as Level 2 does; with it, Level 3 adds the bonus pasture (the report)
        level(3, "Level 3", "Best case", ["site"] if MAIN_PARCEL_ONLY else ["site", "bonus"], "improved"),
    ],
}
os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, "w") as fh:
    fh.write("// Generated by tools/build_capacity_data.py from the pasture worksheet. Do not edit by hand.\n")
    fh.write("window.PASTURE_CAPACITY = " + json.dumps(data, indent=2) + ";\n")
for l in data["levels"]:
    print(l["name"], l["acres"], "ac", l["open"], "/", l["wooded"], "->", l["ce"], "CE")
